import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root));

// --- 1. skin.css: bundle the fonts inline, then append the token stylesheet ---
const FONTS = [
  { file: "assets/fonts/crimson.woff2", family: "Crimson Pro", style: "normal", weight: "200 900" },
  { file: "assets/fonts/crimson-italic.woff2", family: "Crimson Pro", style: "italic", weight: "200 900" },
  { file: "assets/fonts/dmsans.woff2", family: "DM Sans", style: "normal", weight: "100 1000" }
];

const fontFaces = FONTS.map(({ file, family, style, weight }) => {
  const base64 = read(file).toString("base64");
  return `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${base64}) format("woff2")}`;
}).join("\n");

const theme = read("src/theme.css").toString("utf8");
writeFileSync(
  new URL("lib/skin.css", root),
  `/* dsh-claude-workbench — generated by tools/build.mjs; edit src/theme.css instead */\n${fontFaces}\n\n${theme}`
);
console.log(`lib/skin.css: ${(read("lib/skin.css").length / 1024).toFixed(1)} KB`);

// --- 2. client.js: wrap the browser UI in the client-plugin bundle format ---
const source = read("src/panes-ui.js").toString("utf8");
const marker = "export function panesUi(";
const start = source.indexOf(marker);
if (start < 0) throw new Error("panesUi not found in src/panes-ui.js");
const functionSource = source.slice(start + "export ".length).trimEnd();

const bundle = `window.__ModuleLoader__.load({
\tid: "dsh-claude-workbench",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tconst inject = [];
\t\t${functionSource}

\t\tlet started = false;
\t\tasync function start(ctx) {
\t\t\tif (started) return;
\t\t\tstarted = true;
\t\t\tif (window.self !== window.top) return;
\t\t\ttry {
\t\t\t\tconst response = await fetch("/dsh-claude-workbench/boot", { credentials: "include", cache: "no-store" });
\t\t\t\tif (!response.ok) throw new Error("boot payload HTTP " + response.status);
\t\t\t\tpanesUi(await response.json(), ctx);
\t\t\t} catch (error) {
\t\t\t\tconsole.error("[claude-workbench]", error);
\t\t\t}
\t\t}

\t\tfunction apply(ctx) {
\t\t\tstart(ctx);
\t\t\tif (typeof ctx.effect === "function") {
\t\t\t\tctx.effect(() => () => {
\t\t\t\t\ttry { globalThis.__dshPanesTeardown?.(); } catch (error) { /* ignore */ }
\t\t\t\t\tfor (const id of ["dsh-panes", "dsh-panes-toggle", "dsh-panes-style", "dsh-theme-toggle", "dsh-theme-menu"]) {
\t\t\t\t\t\tconst node = document.getElementById(id);
\t\t\t\t\t\tif (node !== null) node.remove();
\t\t\t\t\t}
\t\t\t\t\tconst root = document.getElementById("root");
\t\t\t\t\tif (root !== null) root.style.removeProperty("display");
\t\t\t\t});
\t\t\t}
\t\t}

\t\texports.apply = apply;
\t\texports.inject = inject;
\t\treturn module.exports;
\t}
});
`;

writeFileSync(new URL("lib/client.js", root), bundle);
console.log(`lib/client.js: ${(bundle.length / 1024).toFixed(1)} KB`);
